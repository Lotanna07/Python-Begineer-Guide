message = " hello, python! i would like to learn python programming."

print(message)

#upper(): to uppercase

print(message.upper())


#lower(): to lowercase

print(message.lower())



#strings(): remove unwanted lead 
print(message.strip())


#replace():

print(message.replace("hello", "hi"))


#startswith

print(message.startswith("demo"))

#endwith
print(message.endwith("."))

#count()
print(message.count("python"))